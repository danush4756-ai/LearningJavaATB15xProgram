package Operators;

public class Interview_char {
    static void main(String[] args) {
        char a = 'w', b = 'o';
        System.out.println(a+b);
        System.out.println('w'+10);
        System.out.println('w'+'o'==230);
        System.out.println('w'>'o');
        System.out.println('w'<'o');
    }
}
