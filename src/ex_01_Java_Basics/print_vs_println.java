package ex_01_Java_Basics;

public class print_vs_println {
    static void main() {
        System.out.print("hello");
        System.out.println("darshan"); /*println means print + line. it prints and adds a line so output
        is in one line in this case*/
        System.out.print("hello darshan");//line was already added in previous statement so the output is in new line
    }
}
